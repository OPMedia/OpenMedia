# ============================================================
# fixture-100k-tree.ps1 —— 树形合成 fixture 生成器
#
# 为什么存在（BR-45 教训，docs/perf-baseline.md §5 P4）：
#   早期 fixture 让全部条目共享同一个 CollectionFolder 祖先（单层扁平），
#   BR-45 的 IN 子查询列表 = 全部条目，EXPLAIN 结论（118.5ms 头号慢分支）
#   完全是 fixture 假象；四期已判"跳过 + 结论更正"。
#   本生成器从形态上根治：库 -> 系列 -> 季 -> 集 三层树，
#   每个 CollectionFolder 只管自己的几十~几百条目。
#
# 目标库：openmedia_perf（独立库）。**绝不**写共享库 openmedia。
# 生成器只产出 SQL 文本，不连数据库、无副作用。
#
# 规模默认：150 库 x (电影 400 + 系列 20x4季x10集) = ~125k 条目
# 用法：
#   powershell -ExecutionPolicy Bypass -File tests\perf\fixture-100k-tree.ps1
#   输出 tests\perf\fixture-tree-100k.sql
#   或由 setup-perf-db.ps1 -Fixture tree-100k 自动调用
# ============================================================
