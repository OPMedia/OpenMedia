$total  = 1 + $LibCount + $movie + $series + $season + $episode + 100
if ($total -lt 100000) {
    Write-Warning ("总条目 ~{0} < 100k 门限；调参：-LibCount/-MoviePerLib/-SeriesPerLib/-EpisodesPerSeason" -f $total)
}

